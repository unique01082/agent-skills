#!/usr/bin/env node
// Regenerates references/tools.md from the canonical catalog in @lightmesh/core, plus the host-level tools
// defined by the server (apps/server/src/mcp/toolRegistry.ts). Point it at a LightMesh checkout:
//   node gen_tools_reference.mjs /path/to/lightmesh.baole.space   (or set LIGHTMESH_REPO)
// Build the core package first (npm run build --workspace @lightmesh/core) so dist/ is current.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = process.argv[2] ?? process.env.LIGHTMESH_REPO ?? process.cwd();
const core = await import(path.join(root, 'node_modules/@lightmesh/core/dist/index.js'));

// Keep in sync with toolRegistry.ts — these five are not in the core catalog.
const serverTools = [
  ['session_context', true, 'Open graph and the selected node/edge (resolved to full records). Selection only exists over WebMCP; over remote MCP it is null.', {}, []],
  ['graph_list', true, 'Every graph you own, newest first: id, name, description, last change.', {}, []],
  ['node_set_avatar', false, 'Store a picture for a node (base64, PNG/JPEG/WebP/GIF, ≤2 MB, no SVG) and point metadata.avatar at it.', { nodeId: 'string', imageBase64: 'string', mimeType: 'string' }, ['nodeId', 'imageBase64', 'mimeType']],
  ['file_upload', false, 'Store a file (base64, ≤10 MB, no HTML/SVG/scripts); returns { provider, bucket, key, mimeType, size } to use as a data_add source { type: "object", … }.', { fileBase64: 'string', mimeType: 'string' }, ['fileBase64', 'mimeType']],
  ['node_generate_avatar', false, 'Only when the deployment has an image model. Generates a square avatar from a picture description (≤500 chars) and sets it.', { nodeId: 'string', prompt: 'string' }, ['nodeId', 'prompt']],
];

const typeOf = (s) => (s.enum ? s.enum.map((v) => `"${v}"`).join(' \\| ') : s.type === 'array' ? `${s.items?.type ?? 'object'}[]` : s.type ?? 'any');
const lines = [
  '# LightMesh tool catalog',
  '',
  'Generated by `scripts/gen_tools_reference.mjs` — do not edit by hand. Every graph-scoped tool also',
  'accepts optional `graphId` (omit inside WebMCP to use the open graph; pass it over remote MCP).',
  'Required arguments are marked **bold**.',
  '',
];
const row = (name, ro, desc, props, req) => {
  lines.push(`## \`${name}\` — ${ro ? 'read' : 'write'}`, '', desc, '');
  const entries = Object.entries(props);
  if (!entries.length) return lines.push('No arguments.', '');
  for (const [k, v] of entries) {
    const t = typeof v === 'string' ? v : typeOf(v);
    const d = typeof v === 'string' ? '' : ` — ${(v.description ?? '').replace(/\s+/g, ' ')}`;
    lines.push(`- ${req.includes(k) ? `**${k}**` : k} (\`${t}\`)${d}`);
  }
  lines.push('');
};
for (const t of serverTools) row(...t);
for (const t of core.GRAPH_TOOL_DEFINITIONS) {
  row(t.name, t.annotations?.readOnlyHint, t.description, t.inputSchema.properties ?? {}, t.inputSchema.required ?? []);
}

lines.push(
  '## Nested shapes',
  '',
  '```jsonc',
  '// graph_apply_patch changes[] — applied in order, all-or-nothing',
  '{ "op": "createNode", "id": "orders-db", "node": { "type": "database", "name": "Orders DB", "properties": { "description": "…" } } }',
  '{ "op": "createEdge", "id": "e-api-reads-orders", "edge": { "source": "checkout-api", "target": "orders-db", "type": "reads" } }',
  '{ "op": "updateNode", "id": "checkout-api", "node": { "properties": { "owner": "payments-team" } } }',
  '{ "op": "deleteEdge", "id": "e-old" }',
  '',
  '// data_add source — exactly one shape',
  '{ "type": "inline", "text": "Retries 3x with jitter" }            // kind "text" / "insight"',
  '{ "type": "inline", "base64": "…" }                               // ≤ 2 MB decoded; prefer file_upload',
  '{ "type": "uri", "uri": "https://… | vscode://file/abs/path:42" } // kind "link", "image", "file"',
  '{ "type": "object", "provider": "minio", "bucket": "…", "key": "…" } // from file_upload',
  '',
  '// journey (journey_set / graph_set_info.journey)',
  '{ "title": "…", "description": "…", "steps": [ { "id": "overview", "title": "…", "narration": "…", "nodeIds": [] } ] }',
  '```',
  '',
  'Result envelope for every tool: `{ "status": "success", "data": … }` or',
  '`{ "status": "validation_error" | "conflict" | "not_found" | "failure", "message": "…", "details": … }`.',
  '',
);
writeFileSync(path.join(here, '../references/tools.md'), lines.join('\n'));
console.log(`wrote ${serverTools.length + core.GRAPH_TOOL_DEFINITIONS.length} tools`);
